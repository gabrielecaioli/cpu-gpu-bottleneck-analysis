#!/usr/bin/env python3
"""
Generates the dataset used by CPU versions 2/3 and by all the GPU versions.

The output is a C source file that defines the arrays declared in
include/dataset.h. Compiling the data into the executable guarantees that
every version is benchmarked on exactly the same values, and that no time is
spent generating them at runtime.

Example:
    python3 scripts/generate_dataset.py --seed 1 --out build/data/seed_1/dataset.c
"""

import argparse
import os
import random

VALUES_PER_LINE = 10


def write_array(out, name, values):
    out.write(f"uint32_t {name}[] = {{\n")
    for start in range(0, len(values), VALUES_PER_LINE):
        chunk = values[start:start + VALUES_PER_LINE]
        out.write("    " + ", ".join(map(str, chunk)) + ",\n")
    out.write("};\n")
    out.write(f"const int {name}_count = {len(values)};\n\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, default=1, help="random seed (default: 1)")
    parser.add_argument("--nodes", type=int, default=500_000, help="number of values to insert in the tree (default: 500000)")
    parser.add_argument("--queries", type=int, default=10_000_000, help="number of values to search (default: 10000000)")
    parser.add_argument("--max-value", type=int, default=4_000_000_000, help="values are drawn uniformly from [0, MAX_VALUE] (default: 4e9)")
    parser.add_argument("--out", required=True, help="output .c file")
    args = parser.parse_args()

    if not 0 < args.max_value < 2**32:
        parser.error("--max-value must fit in an unsigned 32-bit integer")

    rng = random.Random(args.seed)
    nodes = [rng.randint(0, args.max_value) for _ in range(args.nodes)]
    queries = [rng.randint(0, args.max_value) for _ in range(args.queries)]

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as out:
        out.write("// Generated by scripts/generate_dataset.py - do not edit.\n")
        out.write(f"// seed={args.seed} nodes={args.nodes} queries={args.queries} max_value={args.max_value}\n\n")
        out.write('#include "dataset.h"\n\n')
        write_array(out, "dataset_nodes", nodes)
        write_array(out, "dataset_queries", queries)

    print(f"Dataset written to {args.out} (seed={args.seed}, nodes={args.nodes}, queries={args.queries})")


if __name__ == "__main__":
    main()
